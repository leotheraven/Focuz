import Foundation
import UserNotifications

@main
struct StoreTests {
    @MainActor static func main() async throws {
        func waitForCondition(timeout: Duration, _ condition: () -> Bool) async throws {
            let clock = ContinuousClock()
            let deadline = clock.now.advanced(by: timeout)
            while !condition() && clock.now < deadline {
                try await Task.sleep(for: .milliseconds(50))
            }
        }

        let root = URL(fileURLWithPath: CommandLine.arguments[1])
        try FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let url = root.appendingPathComponent("state.json")
        let store = GardenStore(url: url)
        let habit = store.engine.state.habits[1]
        precondition(store.change { _ = try $0.check(habit.id, at: Date()) })
        let reopened = GardenStore(url: url)
        precondition(reopened.engine.coins == 10 && reopened.engine.completedCount == 1)
        print("PASS: completed habits survive app restart")

        let historyURL = root.appendingPathComponent("legacy-history.json")
        let historyDay = Calendar.current.startOfDay(for: Date()).addingTimeInterval(3600)
        var legacy = HabitEngine()
        legacy.state.version = 1
        let firstHistoryDay = legacy.calendar.date(byAdding: .day, value: -24, to: historyDay)!
        let historyHabit = Habit(title: "Test activity", symbol: "book", color: "green", target: 1, unit: "page", created: legacy.day(firstHistoryDay))
        try legacy.saveHabit(historyHabit)
        for offset in 0..<24 {
            let day = legacy.calendar.date(byAdding: .day, value: offset, to: firstHistoryDay)!
            legacy.state.checkIns.append(CheckIn(habitID: historyHabit.id, day: legacy.day(day),
                                                 count: 1, target: 1, title: historyHabit.title, rewarded: true))
            legacy.state.chests.insert(legacy.day(day))
        }
        let firstPurchase = Redemption(rewardID: "cactus", title: "Cactus", cost: 240, date: firstHistoryDay)
        legacy.state.redemptions.append(firstPurchase)
        try legacy.addReward(title: "Small reward", cost: 10)
        let smallReward = legacy.state.customRewards[0]
        for offset in 1...20 {
            legacy.state.redemptions.append(Redemption(rewardID: smallReward.id, title: smallReward.title,
                                                       cost: smallReward.cost, date: firstHistoryDay.addingTimeInterval(Double(offset))))
        }
        let oldFertilization = Fertilization(plantID: "cactus", xp: 25, cost: 50,
                                             date: firstHistoryDay.addingTimeInterval(0.5), growthRevision: 3)
        let recentFertilization = Fertilization(plantID: "cactus", xp: 25, cost: 50,
                                                date: firstHistoryDay.addingTimeInterval(21), growthRevision: 3)
        legacy.state.fertilizations = [oldFertilization, recentFertilization]
        var historyFocus = legacy.focusData
        historyFocus.selectedPlant = "cactus"
        historyFocus.growthRevision = 3
        historyFocus.growth["cactus"] = PlantGrowth(points: 50)
        legacy.state.focus = historyFocus
        let legacyBackup = try JSONEncoder().encode(legacy.state)
        try legacyBackup.write(to: historyURL)

        func checkMigratedHistory(_ migrated: HabitEngine) {
            precondition(migrated.state.version == 2 && migrated.recentActivity.count == 20)
            precondition(migrated.state.checkIns.prefix(4).allSatisfy { $0.title == nil && $0.completedAt == nil })
            precondition(migrated.streak(historyHabit, at: historyDay) == 24)
            precondition(migrated.state.redemptions.count == 19 && migrated.fertilizerUses.map(\.id) == [recentFertilization.id])
            precondition(migrated.state.redemptions.allSatisfy { $0.id != firstPurchase.id })
            precondition(migrated.coins == legacy.coins && migrated.owned.contains("cactus"))
            precondition(migrated.currentGrowth.totalPoints == 50)
        }

        let historyStore = GardenStore(url: historyURL)
        checkMigratedHistory(historyStore.engine)
        let compacted = try Data(contentsOf: historyURL)
        let compactedState = try JSONDecoder().decode(GardenState.self, from: compacted)
        checkMigratedHistory(try HabitEngine(state: compactedState).validated())
        let importedHistory = GardenStore(url: root.appendingPathComponent("imported-history.json"))
        try importedHistory.restore(legacyBackup)
        checkMigratedHistory(importedHistory.engine)
        print("PASS: history migration and restore discard old details and preserve streaks, coins, ownership and XP")

        let balance = historyStore.engine.coins
        precondition(historyStore.change { _ = try $0.check(historyHabit.id, at: historyDay) })
        precondition(historyStore.engine.recentActivity.first?.day == historyStore.engine.day(historyDay))
        precondition(historyStore.engine.recentActivity.count == 20 && historyStore.engine.state.checkIns[4].title == nil)
        precondition(historyStore.change { $0.undo(historyHabit.id, at: historyDay) })
        precondition(historyStore.engine.recentActivity.count == 19 && historyStore.engine.coins == balance + 10)
        precondition(historyStore.change { _ = try $0.check(historyHabit.id, at: historyDay.addingTimeInterval(1)) })
        precondition(historyStore.engine.recentActivity.count == 20 && historyStore.engine.coins == balance + 10)
        precondition(historyStore.change { try $0.redeem(smallReward.id, at: historyDay) })
        let finalHistory = GardenStore(url: historyURL).engine
        precondition(finalHistory.coins == balance && finalHistory.owned.contains("cactus"))
        precondition(finalHistory.state.redemptions.count + finalHistory.fertilizerUses.count == 20)
        precondition(finalHistory.state.redemptions.last?.date == historyDay)
        print("PASS: new entries trim both timelines durably and undo does not restore discarded rows or duplicate coins")

        let lifecycleURL = root.appendingPathComponent("lifecycle.json")
        let lifecycle = GardenStore(url: lifecycleURL, preview: reopened.engine)
        precondition(lifecycle.change { $0.pauseHabit(habit.id, paused: true) })
        let paused = GardenStore(url: lifecycleURL)
        precondition(paused.engine.state.habits.first(where: { $0.id == habit.id })?.archived == true)
        print("PASS: paused habit survives app restart")
        precondition(paused.change { $0.pauseHabit(habit.id, paused: false) })
        precondition(GardenStore(url: lifecycleURL).engine.habits(on: Date()).contains(where: { $0.id == habit.id }))
        print("PASS: resumed habit survives app restart")
        precondition(paused.change { $0.deleteHabit(habit.id) })
        let deleted = GardenStore(url: lifecycleURL)
        precondition(deleted.engine.state.habits.first(where: { $0.id == habit.id })?.deleted == true)
        precondition(deleted.engine.coins == 10 && deleted.engine.totalPlantXP == 0 && deleted.engine.completedCount == 1)
        print("PASS: deleted habit and earned rewards survive app restart")
        let sessionURL = root.appendingPathComponent("sessions.json")
        let focusStore = GardenStore(url: sessionURL)
        let start = Date()
        precondition(focusStore.change { try $0.startFocus(minutes: 10, now: start) })
        focusStore.screenLocked()
        focusStore.backgroundFocus()
        precondition(focusStore.engine.focusData.active?.strict == true)
        let resumedFocus = GardenStore(url: sessionURL)
        precondition(resumedFocus.engine.focusData.active?.id == focusStore.engine.focusData.active?.id)
        print("PASS: strict focus survives screen lock/background and process restart")
        resumedFocus.refresh(now: start.addingTimeInterval(600))
        precondition(resumedFocus.engine.focusData.awaitingRest == true && resumedFocus.engine.focusData.active == nil)
        let restPrompt = GardenStore(url: sessionURL)
        precondition(restPrompt.engine.focusData.awaitingRest == true && restPrompt.engine.coins == 10)
        restPrompt.refresh(now: start.addingTimeInterval(3600))
        precondition(restPrompt.engine.focusData.active == nil && restPrompt.engine.coins == 10)
        print("PASS: focus finishes exactly once and rest waits for a tap across restart")
        restPrompt.skipRest()
        precondition(GardenStore(url: sessionURL).engine.focusData.awaitingRest == false)
        print("PASS: skipping rest persists")
        let alertSession = FocusSession(started: start, ends: start.addingTimeInterval(600), minutes: 10, plantID: "sprout", strict: true)
        let alerts = SessionAlert.plans(for: alertSession, now: start)
        precondition(alerts.count == 1 && !alerts[0].isBreak && alerts[0].date == alertSession.ends)
        precondition(SessionAlert.plans(for: alertSession, now: start.addingTimeInterval(700)).isEmpty)
        print("PASS: focus schedules one end alert and never an automatic rest alert")
        var breakSession = alertSession; breakSession.isBreak = true
        precondition(SessionAlert.plans(for: breakSession, now: start).first?.isBreak == true)
        print("PASS: manual rest schedules its own end alert")
        let departure = FocusDeparture(sessionID: alertSession.id, date: start)
        let warning = FocusInterruptionAlert.warning(for: alertSession, departure: departure, now: start)!
        precondition(warning.identifier == FocusInterruptionAlert.warningIdentifier && warning.content.sound == .default)
        precondition((warning.trigger as? UNTimeIntervalNotificationTrigger)?.timeInterval == 5)
        let finalAlert = FocusInterruptionAlert.request(for: alertSession)
        precondition(finalAlert.trigger == nil && finalAlert.content.sound == .default)
        print("PASS: warning waits five seconds and the confirmed failure uses the simple system sound")
        precondition(!departure.shouldInterrupt(alertSession, now: start.addingTimeInterval(9.99)))
        precondition(departure.shouldInterrupt(alertSession, now: start.addingTimeInterval(10)))
        var lockedDeparture = departure; lockedDeparture.lockedAt = start
        precondition(!lockedDeparture.shouldInterrupt(alertSession, now: start.addingTimeInterval(100)))
        precondition(FocusInterruptionAlert.warning(for: alertSession, departure: lockedDeparture, now: start) == nil)
        let finishingSoon = FocusDeparture(sessionID: alertSession.id, date: alertSession.ends.addingTimeInterval(-8))
        precondition(FocusInterruptionAlert.warning(for: alertSession, departure: finishingSoon, now: finishingSoon.date) == nil)
        precondition(!departure.shouldInterrupt(breakSession, now: start.addingTimeInterval(100)))
        print("PASS: grace deadline, detected lock and Rest are classified independently")
        let quick = GardenStore(url: root.appendingPathComponent("quick.json"))
        precondition(quick.change { try $0.startFocus(minutes: 25, now: start) })
        let quickID = quick.engine.focusData.active!.id
        quick.backgroundFocus(now: start.addingTimeInterval(1))
        precondition(quick.engine.focusData.active?.id == quickID && quick.engine.focusData.departure != nil)
        quick.resume(now: start.addingTimeInterval(9))
        precondition(quick.engine.focusData.active?.id == quickID && quick.engine.focusData.departure == nil && quick.engine.focusData.sessions.isEmpty)
        print("PASS: returning within ten seconds keeps the same timer and removes the saved departure")
        let interruptedURL = root.appendingPathComponent("interrupted.json")
        let interrupted = GardenStore(url: interruptedURL)
        precondition(interrupted.change { try $0.startFocus(minutes: 45, now: start) })
        interrupted.backgroundFocus(now: start.addingTimeInterval(100))
        precondition(interrupted.engine.focusData.active != nil)
        interrupted.refresh(now: start.addingTimeInterval(110))
        precondition(interrupted.engine.focusData.active == nil && interrupted.engine.focusData.preferredMinutes == 45)
        precondition(interrupted.engine.coins == 0 && interrupted.engine.currentGrowth.totalPoints == 0 && interrupted.engine.focusData.awaitingRest != true)
        precondition(interrupted.engine.focusData.sessions.last?.endedAt == start.addingTimeInterval(110))
        precondition(interrupted.engine.focusData.sessions.last?.completedSeconds == 110)
        precondition(GardenStore(url: interruptedURL).engine.focusData.sessions.last?.status == "interrupted")
        print("PASS: ten-second departure fails durably with its deadline and elapsed seconds, without rewards")
        let late = GardenStore(url: root.appendingPathComponent("late-lock.json"))
        precondition(late.change { try $0.startFocus(minutes: 25, now: start) })
        let lateID = late.engine.focusData.active!.id
        late.backgroundFocus(now: start.addingTimeInterval(1))
        late.screenLocked(now: start.addingTimeInterval(4))
        late.refresh(now: start.addingTimeInterval(20))
        precondition(late.engine.focusData.active?.id == lateID && late.engine.focusData.departure?.lockedAt != nil)
        precondition(late.engine.focusData.sessions.isEmpty && late.interruptedSession == nil)
        print("PASS: lock arriving AFTER backgrounding cancels the grace failure and keeps the session")
        late.resume(now: start.addingTimeInterval(25))
        late.refresh(now: start.addingTimeInterval(1500))
        precondition(late.engine.coins == 25 && late.engine.currentGrowth.totalPoints == 25)
        print("PASS: a lock-preserved session still completes and awards exactly once")
        let afterDeadline = GardenStore(url: root.appendingPathComponent("very-late-lock.json"))
        precondition(afterDeadline.change { try $0.startFocus(minutes: 25, now: start) })
        let recoveredID = afterDeadline.engine.focusData.active!.id
        afterDeadline.backgroundFocus(now: start.addingTimeInterval(1))
        afterDeadline.refresh(now: start.addingTimeInterval(12))
        precondition(afterDeadline.engine.focusData.sessions.last?.status == "interrupted")
        afterDeadline.screenUnlocked(now: start.addingTimeInterval(13))
        precondition(afterDeadline.engine.focusData.active?.id == recoveredID && afterDeadline.engine.focusData.sessions.isEmpty)
        precondition(afterDeadline.engine.focusData.departure?.lockedAt != nil && afterDeadline.interruptedSession == nil)
        print("PASS: delayed lock/unlock evidence can repair this departure even after the grace deadline")
        let inactive = GardenStore(url: root.appendingPathComponent("inactive.json"))
        precondition(inactive.change { try $0.startFocus(minutes: 25, now: start) })
        inactive.prepareForBackground()
        inactive.resume(now: start.addingTimeInterval(30))
        precondition(inactive.engine.focusData.active != nil && inactive.engine.focusData.departure == nil)
        print("PASS: Control Center or an incoming-call banner alone never starts the departure penalty")
        let reclaimed = GardenStore(url: root.appendingPathComponent("reclaimed.json"))
        precondition(reclaimed.change { try $0.startFocus(minutes: 25, now: start) })
        reclaimed.backgroundFocus(now: start.addingTimeInterval(1))
        reclaimed.backgroundTimeExpired(now: start.addingTimeInterval(4))
        precondition(reclaimed.engine.focusData.active != nil && reclaimed.engine.focusData.departure != nil)
        reclaimed.resume(now: start.addingTimeInterval(7))
        precondition(reclaimed.engine.focusData.active != nil && reclaimed.engine.focusData.sessions.isEmpty)
        print("PASS: early background-time expiration is not treated as a user failure")
        let realNow = Date()
        var suspended = HabitEngine.initial(at: realNow)
        try suspended.startFocus(minutes: 25, now: realNow.addingTimeInterval(-2000))
        precondition(suspended.leaveFocus(at: realNow.addingTimeInterval(-1990)))
        let suspendedURL = root.appendingPathComponent("suspended.json")
        try JSONEncoder().encode(suspended.state).write(to: suspendedURL)
        let cold = GardenStore(url: suspendedURL)
        precondition(cold.engine.focusData.active == nil && cold.engine.focusData.sessions.last?.status == "interrupted" && cold.engine.coins == 0)
        print("PASS: a saved overdue departure is reconciled before completion after termination/relaunch")
        precondition(suspended.recordFocusLock(at: realNow.addingTimeInterval(-1989)))
        let lockedURL = root.appendingPathComponent("suspended-locked.json")
        try JSONEncoder().encode(suspended.state).write(to: lockedURL)
        let coldLocked = GardenStore(url: lockedURL)
        precondition(coldLocked.engine.coins == 25 && coldLocked.engine.currentGrowth.totalPoints == 25)
        coldLocked.refresh()
        precondition(GardenStore(url: lockedURL).engine.coins == 25)
        print("PASS: a persisted locked session can survive suspension/relaunch and earn once")
        let nearEnd = GardenStore(url: root.appendingPathComponent("near-end.json"))
        precondition(nearEnd.change { try $0.startFocus(minutes: 25, now: start) })
        nearEnd.backgroundFocus(now: start.addingTimeInterval(1499))
        nearEnd.refresh(now: start.addingTimeInterval(1505))
        precondition(nearEnd.engine.focusData.active == nil && nearEnd.engine.coins == 25)
        print("PASS: a session finishing inside the allowed grace period completes normally")
        var reminderBackup = reopened.engine
        var reminderHabit = reminderBackup.state.habits[1]
        reminderHabit.reminder = HabitReminder(hour: 7, minute: 15)
        try reminderBackup.saveHabit(reminderHabit)
        let restoredReminders = GardenStore(url: root.appendingPathComponent("reminder-restore.json"))
        try restoredReminders.restore(JSONEncoder().encode(reminderBackup.state))
        precondition(restoredReminders.engine.state.habits[1].reminder == HabitReminder(hour: 7, minute: 15))
        print("PASS: importing a backup preserves individual habit reminder times")
        let plantURL = root.appendingPathComponent("plant-levels.json")
        var legacyPlant = HabitEngine.initial(at: Date())
        legacyPlant.nourish(points:2000)
        let plantStore = GardenStore(url:plantURL, preview:legacyPlant)
        precondition(plantStore.change { $0.state.petName = "Existing plant" })
        let oldPlantReopened = GardenStore(url:plantURL)
        precondition(oldPlantReopened.engine.currentGrowth.totalPoints == 2000 && oldPlantReopened.engine.plantLevel(oldPlantReopened.engine.currentGrowth) < 100)
        print("PASS: old 2000-point plant survives restart with a derived level and unchanged points")
        precondition(oldPlantReopened.change { $0.nourish(points:18000) })
        let maxPlantReopened = GardenStore(url:plantURL)
        precondition(maxPlantReopened.engine.currentGrowth.totalPoints == 20000 && maxPlantReopened.engine.plantLevel(maxPlantReopened.engine.currentGrowth) == 100 && maxPlantReopened.engine.stage(maxPlantReopened.engine.currentGrowth) == 7)
        precondition(maxPlantReopened.engine.coins == 0)
        print("PASS: max plant level persists independently of coin balance")
        let rateURL = root.appendingPathComponent("focus-rate.json")
        let rateStore = GardenStore(url:rateURL)
        precondition(rateStore.change { engine in
            try engine.startFocus(minutes:25, now:Date().addingTimeInterval(-1600))
            try engine.finishFocus(now:Date())
        })
        let rateReopened = GardenStore(url:rateURL)
        precondition(rateReopened.engine.coins == 25 && rateReopened.engine.totalPlantXP == 25 && rateReopened.engine.currentGrowth.totalPoints == 25 && rateReopened.engine.focusMinutes == 25)
        print("PASS: 25-minute focus keeps exactly 25 EXP and 25 coins after restart")
        rateReopened.refresh()
        precondition(GardenStore(url:rateURL).engine.currentGrowth.totalPoints == 25 && rateReopened.engine.coins == 25)
        print("PASS: reopening and refreshing cannot duplicate the new-rate focus award")
        let migrationURL = root.appendingPathComponent("migration.json")
        var oldGarden = rateStore.engine
        oldGarden.nourish(points: 4975)
        oldGarden.state.focus!.growth["cactus"] = PlantGrowth(points: 3000)
        oldGarden.state.focus!.growthRevision = 2
        let beforeReset = try JSONEncoder().encode(oldGarden.state)
        try beforeReset.write(to: migrationURL)
        let migrated = GardenStore(url: migrationURL)
        precondition(!migrated.storageBlocked && migrated.engine.currentGrowth.totalPoints == 0 && migrated.engine.focusData.growth.isEmpty)
        precondition(migrated.engine.coins == 25 && migrated.engine.focusMinutes == 25)
        precondition((try? Data(contentsOf: root.appendingPathComponent("state-before-2.12.json"))) == beforeReset)
        print("PASS: upgrading resets every plant once, keeps rewards/history and backs up the original bytes")
        precondition(migrated.change { $0.nourish(points: 25) })
        precondition(GardenStore(url: migrationURL).engine.currentGrowth.totalPoints == 25)
        precondition((try? Data(contentsOf: root.appendingPathComponent("state-before-2.12.json"))) == beforeReset)
        print("PASS: restarting preserves post-reset EXP and never overwrites the original backup")
        let importedOld = GardenStore(url: root.appendingPathComponent("old-import.json"))
        try importedOld.restore(beforeReset)
        precondition(importedOld.engine.currentGrowth.totalPoints == 0 && importedOld.engine.coins == 25)
        try importedOld.restore(JSONEncoder().encode(migrated.engine.state))
        precondition(importedOld.engine.currentGrowth.totalPoints == 25)
        print("PASS: old backups enter the reset garden while new backups keep their own plant EXP")
        let firstDay = Calendar.current.date(byAdding: .day, value: -4, to: Date())!
        var foodWallet = HabitEngine.initial(at: firstDay)
        let foodHabit = foodWallet.state.habits[1].id
        for offset in 0..<5 {
            _ = try foodWallet.check(foodHabit, at: Calendar.current.date(byAdding: .day, value: offset, to: firstDay)!)
        }
        let foodURL = root.appendingPathComponent("fertilizer.json")
        let foodStore = GardenStore(url: foodURL, preview: foodWallet)
        precondition(foodStore.engine.coins == 50 && foodStore.engine.totalPlantXP == 0)
        let foodQuote = foodStore.engine.fertilizerQuote()!
        foodStore.fertilize(foodQuote)
        precondition(foodStore.engine.coins == 0 && foodStore.engine.currentGrowth.totalPoints == 25 && foodStore.engine.fertilizerUses.count == 1)
        print("PASS: five habits buy one 50-coin fertilizer and grant only its 25 plant XP")
        let foodReopened = GardenStore(url: foodURL)
        foodReopened.refresh()
        precondition(foodReopened.engine.coins == 0 && foodReopened.engine.currentGrowth.totalPoints == 25 && foodReopened.engine.fertilizerUses.count == 1)
        print("PASS: fertilizer deduction and plant XP survive restart without replay or another reset")
        foodReopened.fertilize(foodQuote)
        precondition(foodReopened.engine.coins == 0 && foodReopened.engine.currentGrowth.totalPoints == 25 && foodReopened.engine.fertilizerUses.count == 1)
        print("PASS: insufficient coin balance cannot add fertilizer XP or duplicate its history")
        let foodImported = GardenStore(url: root.appendingPathComponent("food-import.json"))
        try foodImported.restore(JSONEncoder().encode(foodReopened.engine.state))
        precondition(foodImported.engine.coins == 0 && foodImported.engine.currentGrowth.totalPoints == 25 && foodImported.engine.fertilizerUses.count == 1)
        print("PASS: a current-economy backup preserves paid fertilizer and its species XP")
        let foodBlocked = GardenStore(url: root, preview: foodWallet)
        foodBlocked.fertilize(foodQuote)
        precondition(foodBlocked.engine.coins == 50 && foodBlocked.engine.currentGrowth.totalPoints == 0 && foodBlocked.engine.fertilizerUses.isEmpty)
        print("PASS: failed fertilizer save commits neither the coin spend nor the plant XP")
        let blocked = GardenStore(url: root, preview: HabitEngine.initial(at: Date()))
        precondition(!blocked.change { $0.state.petName = "Should not save" })
        precondition(blocked.engine.state.petName == "Mầm")
        print("PASS: failed write does not commit in-memory state")
        let badURL = root.appendingPathComponent("corrupt.json")
        try Data("invalid json".utf8).write(to: badURL)
        let corrupt = GardenStore(url: badURL)
        precondition(corrupt.storageBlocked)
        precondition(!corrupt.change { $0.state.petName = "Overwrite" })
        let preserved = try Data(contentsOf: badURL)
        precondition(String(data: preserved, encoding: .utf8) == "invalid json")
        print("PASS: corrupt save is preserved and cannot be silently overwritten")
        let backup = try JSONEncoder().encode(reopened.engine.state)
        try corrupt.restore(backup)
        precondition(!corrupt.storageBlocked && corrupt.engine.coins == 10)
        print("PASS: valid backup restores progress and recovers blocked storage")
        let waiting = GardenStore(url: root.appendingPathComponent("waiting.json"))
        precondition(waiting.change { try $0.startFocus(minutes: 25, now: Date()) })
        waiting.backgroundFocus()
        precondition(waiting.engine.focusData.active != nil && waiting.engine.focusData.sessions.isEmpty)
        print("PASS: backgrounding no longer destroys a session synchronously")
        let restStore = GardenStore(url: root.appendingPathComponent("rest-background.json"))
        precondition(restStore.change { try $0.startFocus(minutes: 5, isBreak: true, now: Date()) })
        let restID = restStore.engine.focusData.active!.id
        restStore.backgroundFocus()
        precondition(restStore.engine.focusData.active?.id == restID && restStore.engine.focusData.departure == nil)
        print("PASS: backgrounding during Rest does not trigger the strict Focus reset")
        let liveGrace = GardenStore(url: root.appendingPathComponent("live-grace.json"))
        precondition(liveGrace.change { try $0.startFocus(minutes: 25, now: Date()) })
        liveGrace.backgroundFocus()
        precondition(liveGrace.engine.focusData.departure != nil, "Backgrounding must start the grace timer")
        try await waitForCondition(timeout: .seconds(FocusDeparture.gracePeriod + 8)) {
            liveGrace.engine.focusData.active == nil
        }
        precondition(liveGrace.engine.focusData.active == nil && liveGrace.engine.focusData.sessions.last?.status == "interrupted",
                     "The scheduled grace timer must interrupt the active session")
        precondition(afterDeadline.engine.focusData.active?.id == recoveredID)
        print("PASS: the real grace task fails a genuine departure while repaired locked Focus keeps running")
        liveGrace.resume()
        try await waitForCondition(timeout: .seconds(10)) {
            liveGrace.interruptedSession != nil
        }
        precondition(liveGrace.interruptedSession?.id == liveGrace.engine.focusData.sessions.last?.id)
        precondition(liveGrace.engine.focusData.departure?.noticeShown == true)
        print("PASS: confirmed failure shows one foreground notice after the unlock-evidence window")
        liveGrace.dismissFocusInterruption()
        liveGrace.resume()
        try await Task.sleep(for: .seconds(0.1))
        precondition(liveGrace.interruptedSession == nil)
        print("PASS: acknowledging a failure prevents the dialog repeating on every activation")
    }
}
